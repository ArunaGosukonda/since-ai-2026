"""Export the pipeline's danger-phrase patterns for the frontend.

Writes frontend/src/generated/dangerPatterns.json from dsa/facts_keyword.py, so the
phone demo underlines exactly the phrases the pipeline treats as scam signals:

  * sender - who the text claims to be (bank, police, operator, ...)   facts_keyword.SENDER
  * lure   - what it asks for (codes, money transfer, remote access...) facts_keyword.LURE
  * threat - pressure and deadlines                                   facts_keyword.THREAT
  * fee    - small "handling / customs fee" requests                  facts_keyword.FEE

The patterns run against accent-folded lower-case text (see facts_keyword.fold); the
frontend applies the same folding. Lures marked needs_link only count when the text has a
link, as in the pipeline.

Usage:  python3 tools/export_frontend_patterns.py      (re-run after editing facts_keyword.py)
"""
import json
import os
import sys

sys.dont_write_bytecode = True
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from dsa import facts_keyword as fk  # noqa: E402

OUT = os.path.join(ROOT, "frontend", "src", "generated", "dangerPatterns.json")


def main():
    patterns = []
    for kind, p in fk.SENDER:
        patterns.append({"group": "sender", "kind": kind, "pattern": p.pattern, "needs_link": False})
    for kind, needs_link, p in fk.LURE:
        patterns.append({"group": "lure", "kind": kind, "pattern": p.pattern, "needs_link": bool(needs_link)})
    patterns.append({"group": "threat", "kind": "threat", "pattern": fk.THREAT.pattern, "needs_link": False})
    patterns.append({"group": "fee", "kind": "fee", "pattern": fk.FEE.pattern, "needs_link": False})
    out = {
        "source": "dsa/facts_keyword.py (generated by tools/export_frontend_patterns.py - do not edit by hand)",
        "fold": {"ä": "a", "ö": "o", "å": "a", "é": "e", "ü": "u"},
        "link": fk.LINK.pattern,
        "patterns": patterns,
    }
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        json.dump(out, f, ensure_ascii=False, indent=1)
        f.write("\n")
    print("wrote %s (%d patterns)" % (os.path.relpath(OUT, ROOT), len(patterns)))


if __name__ == "__main__":
    main()

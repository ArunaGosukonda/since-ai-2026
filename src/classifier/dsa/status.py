"""Measured model performance, kept in the YAML header of MODEL_STATUS.md.

The header is generated (``bin/dsa status --measure``), never typed by hand;
the weakness checklist below it is written by people and agents and refers
to header metrics as ``metric: `section.key```.

A fingerprint of every file that can change a decision or a measurement
(dsa/*.py except the interface modules, knowledge/*.yaml) is stored with
the numbers, so ``bin/dsa status`` can tell whether they are stale.
"""
import datetime
import glob
import hashlib
import json
import os
import subprocess
import sys
import time

import yaml

from .data import ROOT

PATH = os.path.join(ROOT, "MODEL_STATUS.md")
# modules that only expose or report; editing them cannot change a decision
_NOT_DECISION = {"cli.py", "contract.py", "status.py", "__init__.py"}

# name -> bin/dsa arguments; all held-out-family evaluations except where noted
RUNS = {
    "facts": ["facts", "eval", "--cv", "both"],
    "conversation": ["policy", "eval", "--mode", "multi", "--agent-flags"],
    "conversation_no_flags": ["policy", "eval", "--mode", "multi"],
    "single_turn": ["policy", "eval", "--mode", "single", "--agent-flags"],
}


def decision_files():
    files = [f for f in sorted(glob.glob(os.path.join(ROOT, "dsa", "*.py"))) if os.path.basename(f) not in _NOT_DECISION]
    return files + sorted(glob.glob(os.path.join(ROOT, "knowledge", "*.yaml")))


def fingerprint():
    h = hashlib.sha256()
    for f in decision_files():
        h.update(os.path.relpath(f, ROOT).encode())
        with open(f, "rb") as fh:
            h.update(fh.read())
    return h.hexdigest()[:12]


def _git(*args):
    try:
        return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return None


def read():
    """(header dict, body text) of MODEL_STATUS.md."""
    if not os.path.exists(PATH):
        return {}, ""
    text = open(PATH, encoding="utf-8").read()
    if not text.startswith("---\n"):
        return {}, text
    _, head, body = text.split("---\n", 2)
    return yaml.safe_load(head) or {}, body


def _write(header, body):
    head = yaml.safe_dump(header, sort_keys=False, allow_unicode=True, width=100)
    with open(PATH, "w", encoding="utf-8") as f:
        f.write("---\n# GENERATED by `bin/dsa status --measure`; do not edit by hand.\n" + head + "---\n" + body)


def _pick(block, keys):
    return {k: block[k] for k in keys if k in block}


def _metrics(res):
    f, fr = res["facts"]["results"]["family"], res["facts"]["results"]["random"]
    conv = res["conversation"]["results"]["family"]
    single = res["single_turn"]["results"]["family"]
    policy_keys = ("passed", "action_ok", "under", "risk_ok", "esc_recall", "esc_false_pos",
                   "asked_decisive", "benign_fa", "questions", "unnecessary_q")
    return {
        "facts": {
            "action_ok": f["overall"]["action_ok"],
            "action_ok_before_questions": f["by_view"]["visible"]["action_ok"],
            "action_ok_all_signals": f["by_view"]["full"]["action_ok"],
            "action_ok_all_answered": f["by_view"]["answered"]["action_ok"],
            "twin_action_ok": f["overall"]["twin_action_ok"],
            "benign_false_alarm": f["overall"]["benign_false_alarm"],
            "under_reaction": f["overall"]["under_reaction"],
            "action_ok_seen_families": fr["overall"]["action_ok"],
        },
        "conversation": _pick(conv["overall"], policy_keys) | {
            "twin_passed": conv["twin_vs_single"].get("twin", {}).get("passed"),
            "non_twin_passed": conv["twin_vs_single"].get("single", {}).get("passed"),
            "passed_by_language": {k: v["passed"] for k, v in conv["by_language"].items()},
            "passed_by_journey": {k: v["passed"] for k, v in conv["by_journey"].items()},
        },
        "conversation_no_flags": {"passed": res["conversation_no_flags"]["results"]["family"]["overall"]["passed"]},
        "single_turn": _pick(single["overall"], policy_keys) | {
            "twin_passed": single["twin_vs_single"].get("twin", {}).get("passed"),
        },
        "worst_families": [{"family": w["family"], "passed": w["passed"], "failures": [f"{k} x{n}" for k, n in w["failures"]]}
                           for w in conv["worst_families"]],
    }


def measure():
    """Run every evaluation in parallel through bin/dsa and write the header."""
    t = time.time()
    env = dict(os.environ, PYTHONWARNINGS="ignore")
    jobs = str(max(1, (os.cpu_count() or 1) // len(RUNS)))     # share the CPUs between the parallel runs
    procs = {name: subprocess.Popen([sys.executable, "-m", "dsa.cli", *args, "--jobs", jobs], cwd=ROOT, env=env,
                                    stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)
             for name, args in RUNS.items()}
    res, errors = {}, []
    for name, p in procs.items():
        out, err = p.communicate()
        if p.returncode:
            errors.append(f"{name}: exit {p.returncode}: {err.strip()[-500:]}")
        else:
            res[name] = json.loads(out)
    if errors:
        return {"error": "evaluation failed", "details": errors}
    header = {
        "measured_at": datetime.datetime.now().isoformat(timespec="minutes"),
        "commit": (_git("rev-parse", "--short", "HEAD") or "?") + ("+dirty" if _git("status", "--porcelain", "dsa", "knowledge") else ""),
        "fingerprint": fingerprint(),
        "evaluation": "leave-scenario-family-out CV on dev (7 folds) unless named *_seen_families; "
                      "percentages; conversation = simulated multi-turn with agent flags",
        "commands": {name: "bin/dsa " + " ".join(args) for name, args in RUNS.items()},
        "metrics": _metrics(res),
    }
    _, body = read()
    _write(header, body)
    return status() | {"seconds": round(time.time() - t, 1)}


def metric(header, dotted):
    cur = header.get("metrics") or {}
    for part in dotted.split("."):
        if not isinstance(cur, dict) or part not in cur:
            raise KeyError(dotted)
        cur = cur[part]
    return cur


def status():
    header, _ = read()
    now = fingerprint()
    return {
        "file": os.path.relpath(PATH, ROOT),
        "measured_at": header.get("measured_at"),
        "commit": header.get("commit"),
        "stale": header.get("fingerprint") != now,
        "fingerprint": header.get("fingerprint"),
        "current_fingerprint": now,
        "headline": {k: header.get("metrics", {}).get(s, {}).get(k2)
                     for k, (s, k2) in {"conversation_passed": ("conversation", "passed"),
                                        "single_turn_passed": ("single_turn", "passed"),
                                        "facts_action_ok": ("facts", "action_ok")}.items()} if header else None,
    }
